def plot_residual_histograms(
    ground_truth: np.ndarray,
    prediction: np.ndarray,
    output_path: Path,
    dpi: int,
    histogram_bins: int,
) -> None:
    """Plot one residual histogram for each translation component."""

    figure, axes = plt.subplots(
        3,
        1,
        figsize=(10, 12),
    )

    for axis_index, axis in enumerate(AXES):
        residuals = (
            prediction[:, axis_index]
            - ground_truth[:, axis_index]
        )

        bias = float(np.mean(residuals))

        axes[axis_index].hist(
            residuals,
            bins=histogram_bins,
        )

        axes[axis_index].axvline(
            0.0,
            linestyle="--",
            linewidth=1.2,
            label="Zero residual",
        )

        axes[axis_index].axvline(
            bias,
            linewidth=1.2,
            label=f"Mean residual = {bias:.6f}",
        )

        axes[axis_index].set_xlabel(
            f"Prediction − ground truth, axis {axis}"
        )

        axes[axis_index].set_ylabel("Count")

        axes[axis_index].set_title(
            f"Translation {axis} residual distribution"
        )

        axes[axis_index].grid(alpha=0.3)
        axes[axis_index].legend()

    save_figure(
        figure,
        output_path,
        dpi,
    )


def plot_cumulative_error(
    frames: np.ndarray,
    ground_truth: np.ndarray,
    prediction: np.ndarray,
    output_path: Path,
    dpi: int,
) -> None:
    """Plot cumulative component-wise translation residual."""

    residuals = prediction - ground_truth
    cumulative = np.cumsum(
        residuals,
        axis=0,
    )

    figure, axes = plt.subplots(
        figsize=(14, 7)
    )

    for axis_index, axis in enumerate(AXES):
        axes.plot(
            frames,
            cumulative[:, axis_index],
            label=f"Axis {axis}",
            linewidth=1.1,
        )

    cumulative_norm = np.linalg.norm(
        cumulative,
        axis=1,
    )

    axes.plot(
        frames,
        cumulative_norm,
        label="Cumulative residual norm",
        linewidth=1.4,
        linestyle="--",
    )

    axes.axhline(
        0.0,
        linewidth=1.0,
    )

    axes.set_xlabel("Frame")
    axes.set_ylabel(
        "Cumulative translation residual"
    )

    axes.set_title(
        "Cumulative translation prediction error"
    )

    axes.grid(alpha=0.3)
    axes.legend()

    save_figure(
        figure,
        output_path,
        dpi,
    )


def json_safe(value: object) -> object:
    """Convert NaN and infinity to None for strict JSON output."""

    if isinstance(value, dict):
        return {
            str(key): json_safe(item)
            for key, item in value.items()
        }

    if isinstance(value, list):
        return [
            json_safe(item)
            for item in value
        ]

    if isinstance(value, tuple):
        return [
            json_safe(item)
            for item in value
        ]

    if isinstance(
        value,
        (
            np.floating,
            float,
        ),
    ):
        numeric_value = float(value)

        if not math.isfinite(numeric_value):
            return None

        return numeric_value

    if isinstance(
        value,
        (
            np.integer,
            int,
        ),
    ):
        return int(value)

    return value


def build_summary(
    input_path: Path,
    dataframe: pd.DataFrame,
    axis_statistics: Sequence[AxisStatistics],
    bias_statistics: Sequence[BiasStatistics],
    correlation_statistics: Sequence[
        CorrelationStatistics
    ],
    vector_summary: Mapping[str, object],
) -> Dict[str, object]:
    """Build the JSON analysis summary."""

    axis_by_name = {
        row.axis: asdict(row)
        for row in axis_statistics
    }

    bias_by_name = {
        row.axis: asdict(row)
        for row in bias_statistics
    }

    correlation_by_name = {
        row.axis: asdict(row)
        for row in correlation_statistics
    }

    mean_residual_vector = [
        bias_by_name[axis]["bias"]
        for axis in AXES
    ]

    final_cumulative_error_vector = [
        bias_by_name[axis][
            "cumulative_final_error"
        ]
        for axis in AXES
    ]

    return {
        "input_csv": str(
            input_path.resolve()
        ),
        "sample_count": int(
            len(dataframe)
        ),
        "translation_representation_note": (
            "Statistics describe the translation columns stored in the "
            "input CSV. Interpret them as Cartesian translation only if "
            "the evaluator exported reconstructed Cartesian relative "
            "translation."
        ),
        "residual_definition": (
            "prediction_minus_ground_truth"
        ),
        "axis_statistics": axis_by_name,
        "bias_statistics": bias_by_name,
        "correlation_statistics": correlation_by_name,
        "vector_statistics": dict(
            vector_summary
        ),
        "mean_residual_vector": (
            mean_residual_vector
        ),
        "mean_residual_vector_norm": float(
            np.linalg.norm(
                np.asarray(
                    mean_residual_vector,
                    dtype=np.float64,
                )
            )
        ),
        "final_cumulative_error_vector": (
            final_cumulative_error_vector
        ),
        "final_cumulative_error_vector_norm": float(
            np.linalg.norm(
                np.asarray(
                    final_cumulative_error_vector,
                    dtype=np.float64,
                )
            )
        ),
    }


