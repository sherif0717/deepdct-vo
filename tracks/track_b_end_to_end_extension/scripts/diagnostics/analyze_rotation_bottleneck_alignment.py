def validate_args(
    args: argparse.Namespace,
) -> None:
    if not args.inputs:
        raise ValueError(
            "At least one --input is required."
        )

    for path in args.inputs:
        if not path.is_file():
            raise FileNotFoundError(
                f"Input file does not exist: {path}"
            )

    if args.pairs is not None and not args.pairs.is_file():
        raise FileNotFoundError(
            f"Pair file does not exist: {args.pairs}"
        )

    if args.ridge_alpha < 0:
        raise ValueError(
            "--ridge-alpha cannot be negative."
        )

    if args.sequence_probe_alpha < 0:
        raise ValueError(
            "--sequence-probe-alpha cannot be negative."
        )

    if args.pca_components <= 0:
        raise ValueError(
            "--pca-components must be positive."
        )


def infer_sequence(
    path: Path,
) -> str:
    for component in reversed(
        path.parts[:-1]
    ):
        if re.fullmatch(
            r"\d{1,2}",
            component,
        ):
            return component.zfill(2)

    return path.parent.name


def resolve_npz_key(
    archive: np.lib.npyio.NpzFile,
    candidates: Sequence[str],
    description: str,
) -> str:
    for key in candidates:
        if key in archive.files:
            return key

    raise KeyError(
        f"Missing {description}. "
        f"Accepted keys={list(candidates)}, "
        f"available={archive.files}."
    )


def l2_normalize_rows(
    x: np.ndarray,
    eps: float = 1.0e-12,
) -> np.ndarray:
    norms = np.linalg.norm(
        x,
        axis=1,
        keepdims=True,
    )

    return (
        x
        / np.maximum(
            norms,
            eps,
        )
    )


def load_sequence_block(
    path: Path,
    normalize: bool,
) -> SequenceBlock:
    sequence = infer_sequence(
        path
    )

    with np.load(
        path,
        allow_pickle=False,
    ) as archive:
        representation_key = resolve_npz_key(
            archive,
            (
                "rotation_rep",
                "rotation_representation",
            ),
            "rotation representation",
        )

        rotation_key = resolve_npz_key(
            archive,
            (
                "rotation_gt_array",
                "rotation_gt",
            ),
            "rotation GT",
        )

        translation_key = resolve_npz_key(
            archive,
            (
                "translation_gt_array",
                "translation_gt",
            ),
            "translation GT",
        )

        regime_key = resolve_npz_key(
            archive,
            (
                "motion_regime_array",
                "motion_regime",
            ),
            "motion regime",
        )

        representation = np.asarray(
            archive[
                representation_key
            ],
            dtype=np.float64,
        )

        rotation_gt = np.asarray(
            archive[
                rotation_key
            ],
            dtype=np.float64,
        )

        translation_gt = np.asarray(
            archive[
                translation_key
            ],
            dtype=np.float64,
        )

        motion_regime = np.asarray(
            archive[
                regime_key
            ]
        ).reshape(-1)

    if representation.ndim != 2:
        raise ValueError(
            f"{path}: representation must be [N, D], "
            f"received {representation.shape}."
        )

    n_samples = representation.shape[0]

    if rotation_gt.shape != (
        n_samples,
        3,
    ):
        raise ValueError(
            f"{path}: rotation_gt must be "
            f"({n_samples}, 3), "
            f"received {rotation_gt.shape}."
        )

    if translation_gt.shape != (
        n_samples,
        3,
    ):
        raise ValueError(
            f"{path}: translation_gt must be "
            f"({n_samples}, 3), "
            f"received {translation_gt.shape}."
        )

    if motion_regime.shape != (
        n_samples,
    ):
        raise ValueError(
            f"{path}: motion_regime must be "
            f"({n_samples},), "
            f"received {motion_regime.shape}."
        )

    for name, array in (
        ("representation", representation),
        ("rotation_gt", rotation_gt),
        ("translation_gt", translation_gt),
    ):
        if not np.all(
            np.isfinite(array)
        ):
            raise ValueError(
                f"{path}: {name} contains "
                "NaN or infinity."
            )

    motion_regime = np.rint(
        motion_regime
    ).astype(
        np.int64
    )

    invalid = sorted(
        set(
            motion_regime.tolist()
        )
        - set(
            REGIME_NAMES.keys()
        )
    )

    if invalid:
        raise ValueError(
            f"{path}: invalid motion regime IDs "
            f"{invalid}."
        )

    if normalize:
        representation = (
            l2_normalize_rows(
                representation
            )
        )

    return SequenceBlock(
        sequence=sequence,
        path=path,
        representation=representation,
        rotation_gt=rotation_gt,
        translation_gt=translation_gt,
        motion_regime=motion_regime,
    )


def load_all_blocks(
    paths: Sequence[Path],
    normalize: bool,
) -> List[SequenceBlock]:
    blocks: List[
        SequenceBlock
    ] = []

    expected_dimension: Optional[
        int
    ] = None

    seen_sequences = set()

    for path in paths:
        block = load_sequence_block(
            path=path,
            normalize=normalize,
        )

        if block.sequence in seen_sequences:
            raise ValueError(
                "Duplicate sequence export supplied: "
                f"{block.sequence}."
            )

        seen_sequences.add(
            block.sequence
        )

        if expected_dimension is None:
            expected_dimension = int(
                block.representation.shape[
                    1
                ]
            )

        elif (
            block.representation.shape[
                1
            ]
            != expected_dimension
        ):
            raise ValueError(
                "Representation dimensions do not "
                "match across inputs. "
                f"Expected {expected_dimension}, "
                f"received "
                f"{block.representation.shape[1]} "
                f"for sequence {block.sequence}."
            )

        blocks.append(
            block
        )

        print(
            f"Loaded sequence "
            f"{block.sequence}: "
            f"N={block.representation.shape[0]} "
            f"D={block.representation.shape[1]}"
        )

    return blocks


def concatenate_blocks(
    blocks: Sequence[SequenceBlock],
) -> Tuple[
    np.ndarray,
    np.ndarray,
    np.ndarray,
    np.ndarray,
    np.ndarray,
]:
    representations = np.concatenate(
        [
            block.representation
            for block in blocks
        ],
        axis=0,
    )

    rotations = np.concatenate(
        [
            block.rotation_gt
            for block in blocks
        ],
        axis=0,
    )

    translations = np.concatenate(
        [
            block.translation_gt
            for block in blocks
        ],
        axis=0,
    )

    regimes = np.concatenate(
        [
            block.motion_regime
            for block in blocks
        ],
        axis=0,
    )

    sequences = np.concatenate(
        [
            np.asarray(
                [
                    block.sequence
                ]
                * block.representation.shape[
                    0
                ]
            )
            for block in blocks
        ],
        axis=0,
    )

    return (
        representations,
        rotations,
        translations,
        regimes,
        sequences,
    )


def centroid(
    x: np.ndarray,
) -> np.ndarray:
    if x.shape[0] == 0:
        raise ValueError(
            "Cannot calculate centroid of "
            "an empty array."
        )

    return x.mean(
        axis=0
    )


def rms_scale(
    x: np.ndarray,
) -> float:
    if x.size == 0:
        return float("nan")

    return float(
        np.sqrt(
            np.mean(
                x ** 2
            )
        )
    )


def total_variance(
    x: np.ndarray,
) -> float:
    if x.shape[0] <= 1:
        return 0.0

    return float(
        np.var(
            x,
            axis=0,
            ddof=1,
        ).sum()
    )


def within_spread(
    x: np.ndarray,
) -> float:
    if x.shape[0] == 0:
        return float("nan")

    c = centroid(
        x
    )

    return float(
        np.sqrt(
            np.mean(
                np.sum(
                    (
                        x
                        - c
                    )
                    ** 2,
                    axis=1,
                )
            )
        )
    )


def cosine_similarity(
    a: np.ndarray,
    b: np.ndarray,
    eps: float = 1.0e-12,
) -> float:
    denominator = (
        np.linalg.norm(a)
        * np.linalg.norm(b)
    )

    if denominator <= eps:
        return float("nan")

    return float(
        np.dot(a, b)
        / denominator
    )


def angle_degrees(
    a: np.ndarray,
    b: np.ndarray,
) -> float:
    cosine = cosine_similarity(
        a,
        b,
    )

    if not math.isfinite(
        cosine
    ):
        return float("nan")

    cosine = float(
        np.clip(
            cosine,
            -1.0,
            1.0,
        )
    )

    return float(
        np.degrees(
            np.arccos(
                cosine
            )
        )
    )


def write_csv(
    path: Path,
    rows: Sequence[
        Mapping[str, object]
    ],
) -> None:
    if not rows:
        return

    fieldnames = list(
        rows[0].keys()
    )

    with path.open(
        "w",
        encoding="utf-8",
        newline="",
    ) as file:
        writer = csv.DictWriter(
            file,
            fieldnames=fieldnames,
        )

        writer.writeheader()

        for row in rows:
            writer.writerow(
                row
            )


def representation_statistics(
    x: np.ndarray,
) -> Dict[str, object]:
    norms = np.linalg.norm(
        x,
        axis=1,
    )

    c = centroid(
        x
    )

    return {
        "n": int(
            x.shape[0]
        ),
        "dimension": int(
            x.shape[1]
        ),
        "mean_norm": float(
            norms.mean()
        ),
        "std_norm": float(
            norms.std()
        ),
        "centroid_norm": float(
            np.linalg.norm(c)
        ),
        "within_spread": (
            within_spread(x)
        ),
        "total_variance": (
            total_variance(x)
        ),
        "rms_scale": (
            rms_scale(x)
        ),
        "minimum": float(
            np.min(x)
        ),
        "maximum": float(
            np.max(x)
        ),
    }


def compute_sequence_statistics(
    blocks: Sequence[SequenceBlock],
) -> List[
    Dict[str, object]
]:
    rows: List[
        Dict[str, object]
    ] = []

    for block in sorted(
        blocks,
        key=lambda item: item.sequence,
    ):
        stats = representation_statistics(
            block.representation
        )

        row = {
            "sequence": (
                block.sequence
            ),
            **stats,
        }

        rows.append(
            row
        )

    return rows


def compute_regime_statistics(
    representations: np.ndarray,
    regimes: np.ndarray,
) -> List[
    Dict[str, object]
]:
    rows: List[
        Dict[str, object]
    ] = []

    for regime in sorted(
        REGIME_NAMES
    ):
        mask = (
            regimes == regime
        )

        if not np.any(
            mask
        ):
            continue

        stats = (
            representation_statistics(
                representations[
                    mask
                ]
            )
        )

        rows.append(
            {
                "regime": regime,
                "regime_name": (
                    REGIME_NAMES[
                        regime
                    ]
                ),
                **stats,
            }
        )

    return rows


def compute_sequence_regime_centroids(
    blocks: Sequence[SequenceBlock],
) -> Tuple[
    List[Dict[str, object]],
    Dict[
        Tuple[str, int],
        np.ndarray,
    ],
]:
    rows: List[
        Dict[str, object]
    ] = []

    centroids: Dict[
        Tuple[str, int],
        np.ndarray,
    ] = {}

    for block in sorted(
        blocks,
        key=lambda item: item.sequence,
    ):
        for regime in sorted(
            REGIME_NAMES
        ):
            mask = (
                block.motion_regime
                == regime
            )

            if not np.any(
                mask
            ):
                continue

            subset = (
                block.representation[
                    mask
                ]
            )

            c = centroid(
                subset
            )

            centroids[
                (
                    block.sequence,
                    regime,
                )
            ] = c

            rows.append(
                {
                    "sequence": (
                        block.sequence
                    ),
                    "regime": regime,
                    "regime_name": (
                        REGIME_NAMES[
                            regime
                        ]
                    ),
                    "n": int(
                        subset.shape[0]
                    ),
                    "centroid_norm": float(
                        np.linalg.norm(c)
                    ),
                    "within_spread": (
                        within_spread(
                            subset
                        )
                    ),
                }
            )

    return (
        rows,
        centroids,
    )


def compute_centroid_distances(
    centroids: Mapping[
        Tuple[str, int],
        np.ndarray,
    ],
) -> List[
    Dict[str, object]
]:
    keys = sorted(
        centroids.keys()
    )

    rows: List[
        Dict[str, object]
    ] = []

    for i, first_key in enumerate(
        keys
    ):
        sequence_a, regime_a = (
            first_key
        )

        centroid_a = (
            centroids[
                first_key
            ]
        )

        for second_key in keys[
            i + 1 :
        ]:
            sequence_b, regime_b = (
                second_key
            )

            centroid_b = (
                centroids[
                    second_key
                ]
            )

            distance = float(
                np.linalg.norm(
                    centroid_a
                    - centroid_b
                )
            )

            rows.append(
                {
                    "sequence_a": (
                        sequence_a
                    ),
                    "regime_a": (
                        regime_a
                    ),
                    "regime_a_name": (
                        REGIME_NAMES[
                            regime_a
                        ]
                    ),
                    "sequence_b": (
                        sequence_b
                    ),
                    "regime_b": (
                        regime_b
                    ),
                    "regime_b_name": (
                        REGIME_NAMES[
                            regime_b
                        ]
                    ),
                    "same_sequence": int(
                        sequence_a
                        == sequence_b
                    ),
                    "same_regime": int(
                        regime_a
                        == regime_b
                    ),
                    "euclidean_distance": (
                        distance
                    ),
                    "cosine_similarity": (
                        cosine_similarity(
                            centroid_a,
                            centroid_b,
                        )
                    ),
                    "angle_degrees": (
                        angle_degrees(
                            centroid_a,
                            centroid_b,
                        )
                    ),
                }
            )

    return rows


def ridge_fit(
    x: np.ndarray,
    y: np.ndarray,
    alpha: float,
) -> Tuple[
    np.ndarray,
    np.ndarray,
]:
    """Fit ridge with an unregularized intercept."""

    if x.ndim != 2:
        raise ValueError(
            "x must be 2-D."
        )

    if y.ndim == 1:
        y = y[:, None]

    x_mean = x.mean(
        axis=0,
        keepdims=True,
    )

    y_mean = y.mean(
        axis=0,
        keepdims=True,
    )

    xc = (
        x
        - x_mean
    )

    yc = (
        y
        - y_mean
    )

    dimension = (
        x.shape[1]
    )

    lhs = (
        xc.T @ xc
        + alpha
        * np.eye(
            dimension,
            dtype=np.float64,
        )
    )

    rhs = (
        xc.T
        @ yc
    )

    weights = np.linalg.solve(
        lhs,
        rhs,
    )

    bias = (
        y_mean
        - x_mean
        @ weights
    ).reshape(
        -1
    )

    return (
        weights,
        bias,
    )


def ridge_predict(
    x: np.ndarray,
    weights: np.ndarray,
    bias: np.ndarray,
) -> np.ndarray:
    return (
        x
        @ weights
        + bias
    )


def rmse(
    prediction: np.ndarray,
    target: np.ndarray,
) -> float:
    return float(
        np.sqrt(
            np.mean(
                (
                    prediction
                    - target
                )
                ** 2
            )
        )
    )


def mae(
    prediction: np.ndarray,
    target: np.ndarray,
) -> float:
    return float(
        np.mean(
            np.abs(
                prediction
                - target
            )
        )
    )


def safe_corr(
    first: np.ndarray,
    second: np.ndarray,
) -> float:
    first = np.asarray(
        first
    ).reshape(-1)

    second = np.asarray(
        second
    ).reshape(-1)

    if first.size < 2:
        return float("nan")

    if (
        np.std(first)
        <= 1.0e-12
        or np.std(second)
        <= 1.0e-12
    ):
        return float("nan")

    return float(
        np.corrcoef(
            first,
            second,
        )[0, 1]
    )


def mask_sequences(
    sequences: np.ndarray,
    selected: Sequence[str],
) -> np.ndarray:
    normalized = {
        str(sequence).zfill(2)
        for sequence in selected
    }

    return np.asarray(
        [
            str(value).zfill(2)
            in normalized
            for value in sequences
        ],
        dtype=bool,
    )


def evaluate_rotation_probe(
    representations: np.ndarray,
    rotations: np.ndarray,
    sequences: np.ndarray,
    train_sequences: Sequence[str],
    evaluation_sequences: Sequence[str],
    alpha: float,
    split_name: str,
) -> Dict[str, object]:
    train_mask = mask_sequences(
        sequences,
        train_sequences,
    )

    evaluation_mask = mask_sequences(
        sequences,
        evaluation_sequences,
    )

    if not np.any(
        train_mask
    ):
        raise RuntimeError(
            "Rotation probe contains no "
            "training samples."
        )

    if not np.any(
        evaluation_mask
    ):
        raise RuntimeError(
            f"Rotation probe contains no "
            f"{split_name} samples."
        )

    weights, bias = ridge_fit(
        representations[
            train_mask
        ],
        rotations[
            train_mask
        ],
        alpha=alpha,
    )

    prediction = ridge_predict(
        representations[
            evaluation_mask
        ],
        weights,
        bias,
    )

    target = rotations[
        evaluation_mask
    ]

    return {
        "split": split_name,
        "train_n": int(
            np.count_nonzero(
                train_mask
            )
        ),
        "test_n": int(
            np.count_nonzero(
                evaluation_mask
            )
        ),
        "alpha": float(
            alpha
        ),
        "vector_rmse": rmse(
            prediction,
            target,
        ),
        "vector_mae": mae(
            prediction,
            target,
        ),
        "x_rmse": rmse(
            prediction[:, 0],
            target[:, 0],
        ),
        "y_rmse": rmse(
            prediction[:, 1],
            target[:, 1],
        ),
        "z_rmse": rmse(
            prediction[:, 2],
            target[:, 2],
        ),
        "x_corr": safe_corr(
            prediction[:, 0],
            target[:, 0],
        ),
        "y_corr": safe_corr(
            prediction[:, 1],
            target[:, 1],
        ),
        "z_corr": safe_corr(
            prediction[:, 2],
            target[:, 2],
        ),
    }


def one_hot(
    labels: np.ndarray,
    classes: Sequence[str],
) -> np.ndarray:
    class_to_index = {
        value: index
        for index, value in enumerate(
            classes
        )
    }

    result = np.zeros(
        (
            labels.shape[0],
            len(classes),
        ),
        dtype=np.float64,
    )

    for row_index, label in enumerate(
        labels
    ):
        result[
            row_index,
            class_to_index[
                str(label)
            ],
        ] = 1.0

    return result


def sequence_probe(
    representations: np.ndarray,
    sequences: np.ndarray,
    alpha: float,
) -> Dict[str, object]:
    classes = sorted(
        {
            str(value)
            for value in sequences
        }
    )

    targets = one_hot(
        sequences,
        classes,
    )

    weights, bias = ridge_fit(
        representations,
        targets,
        alpha=alpha,
    )

    scores = ridge_predict(
        representations,
        weights,
        bias,
    )

    predicted_indices = np.argmax(
        scores,
        axis=1,
    )

    true_indices = np.asarray(
        [
            classes.index(
                str(value)
            )
            for value in sequences
        ],
        dtype=np.int64,
    )

    accuracy = float(
        np.mean(
            predicted_indices
            == true_indices
        )
    )

    chance = (
        1.0
        / len(classes)
    )

    return {
        "n": int(
            representations.shape[0]
        ),
        "num_sequences": int(
            len(classes)
        ),
        "alpha": float(
            alpha
        ),
        "training_accuracy": (
            accuracy
        ),
        "chance_accuracy": float(
            chance
        ),
        "accuracy_minus_chance": float(
            accuracy
            - chance
        ),
    }


def compute_pca(
    representations: np.ndarray,
    requested_components: int,
) -> Dict[str, np.ndarray]:
    mean = representations.mean(
        axis=0,
        keepdims=True,
    )

    centered = (
        representations
        - mean
    )

    _, singular_values, vt = (
        np.linalg.svd(
            centered,
            full_matrices=False,
        )
    )

    maximum_components = min(
        requested_components,
        vt.shape[0],
    )

    components = vt[
        :maximum_components
    ]

    projected = (
        centered
        @ components.T
    )

    if representations.shape[0] > 1:
        explained_variance = (
            singular_values ** 2
            / (
                representations.shape[0]
                - 1
            )
        )
    else:
        explained_variance = (
            singular_values ** 2
        )

    total = float(
        explained_variance.sum()
    )

    if total > 0:
        explained_ratio = (
            explained_variance
            / total
        )
    else:
        explained_ratio = (
            np.zeros_like(
                explained_variance
            )
        )

    return {
        "mean": mean.squeeze(0),
        "components": components,
        "projected": projected,
        "explained_variance": (
            explained_variance[
                :maximum_components
            ]
        ),
        "explained_variance_ratio": (
            explained_ratio[
                :maximum_components
            ]
        ),
    }


def summarize_centroid_geometry(
    centroid_rows: Sequence[
        Mapping[str, object]
    ],
) -> Dict[str, float]:
    same_regime_cross_sequence = [
        float(
            row[
                "euclidean_distance"
            ]
        )
        for row in centroid_rows
        if (
            int(
                row[
                    "same_regime"
                ]
            )
            == 1
            and int(
                row[
                    "same_sequence"
                ]
            )
            == 0
        )
    ]

    different_regime_cross_sequence = [
        float(
            row[
                "euclidean_distance"
            ]
        )
        for row in centroid_rows
        if (
            int(
                row[
                    "same_regime"
                ]
            )
            == 0
            and int(
                row[
                    "same_sequence"
                ]
            )
            == 0
        )
    ]

    return {
        "same_regime_cross_sequence_distance": (
            float(
                np.mean(
                    same_regime_cross_sequence
                )
            )
            if same_regime_cross_sequence
            else float("nan")
        ),
        "different_regime_cross_sequence_distance": (
            float(
                np.mean(
                    different_regime_cross_sequence
                )
            )
            if different_regime_cross_sequence
            else float("nan")
        ),
    }


def analyze_pair_archive(
    path: Path,
) -> Tuple[
    List[Dict[str, object]],
    Dict[str, float],
]:
    with np.load(
        path,
        allow_pickle=False,
    ) as archive:
        required = {
            "pair_label",
            "same_regime",
            "same_sequence",
            "euclidean_distance",
            "cosine_similarity",
        }

        missing = required.difference(
            archive.files
        )

        if missing:
            raise KeyError(
                f"{path} missing pair keys: "
                f"{sorted(missing)}."
            )

        pair_label = np.asarray(
            archive[
                "pair_label"
            ]
        ).reshape(-1)

        same_regime = np.asarray(
            archive[
                "same_regime"
            ]
        ).reshape(-1)

        same_sequence = np.asarray(
            archive[
                "same_sequence"
            ]
        ).reshape(-1)

        euclidean = np.asarray(
            archive[
                "euclidean_distance"
            ],
            dtype=np.float64,
        ).reshape(-1)

        cosine = np.asarray(
            archive[
                "cosine_similarity"
            ],
            dtype=np.float64,
        ).reshape(-1)

    n = pair_label.shape[0]

    for array in (
        same_regime,
        same_sequence,
        euclidean,
        cosine,
    ):
        if array.shape[0] != n:
            raise ValueError(
                "Pair archive arrays have "
                "inconsistent lengths."
            )

    rows: List[
        Dict[str, object]
    ] = []

    for label_value, name in (
        (
            1,
            "positive_same_regime",
        ),
        (
            0,
            "negative_different_regime",
        ),
    ):
        mask = (
            pair_label
            == label_value
        )

        if not np.any(
            mask
        ):
            continue

        rows.append(
            {
                "pair_type": name,
                "n": int(
                    np.count_nonzero(
                        mask
                    )
                ),
                "mean_euclidean_distance": float(
                    np.mean(
                        euclidean[
                            mask
                        ]
                    )
                ),
                "std_euclidean_distance": float(
                    np.std(
                        euclidean[
                            mask
                        ]
                    )
                ),
                "mean_cosine_similarity": float(
                    np.mean(
                        cosine[
                            mask
                        ]
                    )
                ),
                "std_cosine_similarity": float(
                    np.std(
                        cosine[
                            mask
                        ]
                    )
                ),
                "cross_sequence_fraction": float(
                    np.mean(
                        ~same_sequence[
                            mask
                        ].astype(bool)
                    )
                ),
            }
        )

    positive_mask = (
        pair_label == 1
    )

    negative_mask = (
        pair_label == 0
    )

    positive_distance = (
        float(
            np.mean(
                euclidean[
                    positive_mask
                ]
            )
        )
        if np.any(
            positive_mask
        )
        else float("nan")
    )

    negative_distance = (
        float(
            np.mean(
                euclidean[
                    negative_mask
                ]
            )
        )
        if np.any(
            negative_mask
        )
        else float("nan")
    )

    positive_cosine = (
        float(
            np.mean(
                cosine[
                    positive_mask
                ]
            )
        )
        if np.any(
            positive_mask
        )
        else float("nan")
    )

    negative_cosine = (
        float(
            np.mean(
                cosine[
                    negative_mask
                ]
            )
        )
        if np.any(
            negative_mask
        )
        else float("nan")
    )

    summary = {
        "positive_mean_distance": (
            positive_distance
        ),
        "negative_mean_distance": (
            negative_distance
        ),
        "distance_margin": (
            negative_distance
            - positive_distance
        ),
        "positive_mean_cosine": (
            positive_cosine
        ),
        "negative_mean_cosine": (
            negative_cosine
        ),
        "cosine_margin": (
            positive_cosine
            - negative_cosine
        ),
    }

    return (
        rows,
        summary,
    )


def format_float(
    value: float,
    digits: int = 8,
) -> str:
    if not math.isfinite(
        value
    ):
        return "nan"

    return (
        f"{value:.{digits}f}"
    )


