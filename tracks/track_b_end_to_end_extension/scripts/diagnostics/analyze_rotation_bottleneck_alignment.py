#!/usr/bin/env python3
"""Analyze compact rotation bottleneck geometry and motion-conditioned alignment.

This script is the final post-training analysis for the combined experiment:

    (1) compact/task-relevant rotation bottleneck
    (2) motion-conditioned representation consistency/alignment

It analyzes exported compact rotation representations and optionally the
pair archive produced by:

    scripts/build_rotation_motion_alignment_pairs.py

Expected per-sequence NPZ
-------------------------
Each ``rotation_representations.npz`` should contain:

    rotation_rep
        Compact rotation representation z_R.
        Shape: [N, D]

    rotation_gt_array or rotation_gt
        Ground-truth relative rotations.
        Shape: [N, 3]

    translation_gt_array or translation_gt
        Ground-truth relative translations.
        Shape: [N, 3]

    motion_regime_array or motion_regime
        Motion regime assignment derived using training-set thresholds.
        Shape: [N]

        0 = low
        1 = medium
        2 = high

Optional pair NPZ
-----------------
The output from ``build_rotation_motion_alignment_pairs.py``:

    anchor_rep
    partner_rep
    pair_label
    anchor_regime
    partner_regime
    same_regime
    same_sequence
    euclidean_distance
    cosine_similarity

Questions answered
------------------
1. Is the bottleneck numerically healthy?
2. How much representation variance is retained?
3. Can rotation still be decoded from z_R?
4. Do representations separate by motion regime?
5. Are same-regime representations aligned across sequences?
6. Does cross-sequence alignment improve relative to regime mismatch?
7. How much sequence identity remains linearly decodable?
8. Does sequence 10 occupy the same regime-conditioned geometry as
   training sequences?

Example
-------
python3 scripts/analyze_rotation_bottleneck_alignment.py \\
    --input experiments/rotation_alignment/00/rotation_representations.npz \\
    --input experiments/rotation_alignment/01/rotation_representations.npz \\
    --input experiments/rotation_alignment/02/rotation_representations.npz \\
    --input experiments/rotation_alignment/03/rotation_representations.npz \\
    --input experiments/rotation_alignment/04/rotation_representations.npz \\
    --input experiments/rotation_alignment/05/rotation_representations.npz \\
    --input experiments/rotation_alignment/06/rotation_representations.npz \\
    --input experiments/rotation_alignment/07/rotation_representations.npz \\
    --input experiments/rotation_alignment/08/rotation_representations.npz \\
    --input experiments/rotation_alignment/09/rotation_representations.npz \\
    --input experiments/rotation_alignment/10/rotation_representations.npz \\
    --train-sequences 00 01 02 03 04 05 06 07 08 \\
    --validation-sequences 09 \\
    --test-sequences 10 \\
    --pairs \
        experiments/rotation_motion_alignment_pairs/rotation_motion_alignment_pairs.npz \\
    --output-dir experiments/rotation_bottleneck_alignment_analysis

Outputs
-------
<output-dir>/
├── analysis_summary.txt
├── representation_statistics.csv
├── regime_statistics.csv
├── sequence_statistics.csv
├── sequence_regime_centroids.csv
├── centroid_distances.csv
├── rotation_linear_probe.csv
├── sequence_probe.csv
├── pair_geometry.csv
└── principal_components.npz

No model parameters are modified.
"""

from __future__ import annotations

import argparse
import csv
import math
import re
from dataclasses import dataclass
from pathlib import Path
from typing import Dict, Iterable, List, Mapping, Optional, Sequence, Tuple

import numpy as np


REGIME_NAMES = {
    0: "low",
    1: "medium",
    2: "high",
}


@dataclass(frozen=True)
class SequenceBlock:
    """One sequence's exported representation data."""

    sequence: str
    path: Path
    representation: np.ndarray
    rotation_gt: np.ndarray
    translation_gt: np.ndarray
    motion_regime: np.ndarray


